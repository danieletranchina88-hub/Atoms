/** Elettroni di valenza per le strutture di Lewis (gruppi principali: 1–8; metalli di transizione: s + d). */
export function valenceElectrons(Z) {
  const shells = [2, 10, 18, 36, 54, 86, 118];
  let prev = 0;
  for (const s of shells) {
    if (Z <= s) {
      const k = Z - prev;
      if (s - prev === 2) return k;          // H, He
      if (s - prev === 8) return k;          // periodi 2 e 3
      if (k <= 2) return k;                  // gruppi 1–2
      if (s - prev === 18) return k <= 12 ? k : k - 10; // blocco d: s+d; blocco p: gruppo − 10
      if (k <= 16) return k;                 // periodi 6–7, blocco f: 4f/5f + 5d/6d + s
      if (k <= 26) return k - 14;            // blocco d (Lu–Hg, Lr–Cn)
      return k - 24;                         // blocco p
    }
    prev = s;
  }
  return 0;
}

